'''
Helpers for working with CFTS data: parsing the metadata encoded in a dataset
filename, and reshaping the frames the loaders return.

The loaders themselves are in `cftsdata.loaders`. This module deliberately
depends only on the standard library, numpy, pandas and psiaudio so that it
stays cheap to import from analysis code; nothing here may import from the
`summarize_*` modules, which pull in matplotlib and friends.
'''
import datetime as dt
from functools import wraps
import numbers
import re

import numpy as np
import pandas as pd

from psiaudio import util


class BadFilenameException(Exception):

    def __init__(self, filename):
        self.filename = filename

    def __str__(self):
        return f'Bad filename: {self.filename}'


# Parser for the filename generated by the CFTS launcher.
P_PSI_FILENAME = re.compile(
	r'^(?P<datetime>\d{8}-\d{6})\s'
	r'(?P<experimenter>\w+)\s'
	r'(?P<animal_id>[-\w]+)\s'
	r'((?P<ear>left|right)\s)?(?P<note>.*\s)?'
	r'(?P<experiment_type>(?:abr|dpoae|efr|memr|inear|dpgram|dual_dpoae|mlr_llr)(_\w+)?).*$'
)


def parse_psi_filename(filename):
    try:
        groups = P_PSI_FILENAME.match(filename.stem).groupdict()
        groups['datetime'] = dt.datetime.strptime(groups['datetime'], '%Y%m%d-%H%M%S')
        groups['date'] = pd.to_datetime(groups['datetime'].date())
        groups['time'] = groups['datetime'].time()
        groups['side'] = groups['ear']
        return groups
    except AttributeError:
        raise ValueError(f'Could not parse {filename.stem}')


def to_long(df, name='signal', time_name='timepoint'):
    '''
    Reshape a wide waveform DataFrame to long format

    The waveform loaders (e.g., `cftsdata.loaders.abr.waveforms`) return one
    row per stimulus and one column per timepoint. This converts that to one
    row per sample, which is what most plotting libraries expect.

    Parameters
    ----------
    df : pd.DataFrame
        Waveforms, one column per timepoint.
    name : str
        Name to give the column containing the sample values.
    time_name : str
        Name to give the column containing the timepoints.
    '''
    return df.rename_axis(columns=time_name) \
        .stack() \
        .rename(name) \
        .reset_index()


def coerce_frequency(columns, octave_step, si_prefix='', standardize=True):
    '''
    Decorator that coerces frequencies in the returned DataFrame to the
    nearest octave.

    Parameters
    ----------
    columns : {str, list of string}
        Name or names of columns containing frequencies to coerce.
    octave_step : float
        Octave step to coerce frequencies.
    si_prefix : {'', 'k', list of string}
        Ensure that coercion is based on expected scale given SI unit. If list,
        must be one of the valid choices listed above. See
        `psiaudio.util.nearest_octave` for more information.
    standardize : bool
        If True, convert all units to integer units of Hz. This helps with
        joining dataframes.
    '''
    if isinstance(columns, str):
        columns = [columns]
    if isinstance(si_prefix, str):
        si_prefix = [si_prefix] * len(columns)
    if len(columns) != len(si_prefix):
        raise ValueError('Length of si_prefix should match length of columns')

    def inner(fn):
        @wraps(fn)
        def wrapper(*args, **kwargs):
            result = fn(*args, **kwargs)
            for c, si in zip(columns, si_prefix):
                try:
                    # Make sure values are numeric and greater than 0. Less
                    # than 0 is used as a flag for some special stimuli (e.g.,
                    # clicks).
                    m = [(isinstance(v, numbers.Number) and (v > 0)) for v in result[c]]
                    r = util.nearest_octave(result.loc[m, c].astype('float'), octave_step, si)
                    if standardize:
                        if si == '':
                            pass
                        elif si == 'k':
                            r = r * 1e3
                        else:
                            raise ValueError(f'Unrecognized SI unit: {si}')
                        r = np.round(r).astype('int')
                    result.loc[m, c] = r
                except KeyError as e:
                    cols = ', '.join(result.columns)
                    raise KeyError(f'No column named "{c}". Valid columns are {cols}.') from e
            return result
        return wrapper
    return inner
