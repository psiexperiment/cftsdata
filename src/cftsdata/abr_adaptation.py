'''
Interface for reading ABR adaptation data generated by psiexperiment

Each trial is a train of `n_bursts` tone bursts (or clicks) presented at
`rate` per second followed by a pause (`sequence_pause`). The train is saved
as a single epoch, which we extract (and filter) as a whole and then cut into
one repeat per burst, as psiexperiment does online.

Example
-------

.. code-block:: python

    from cftsdata import abr_adaptation
    filename = '20261027-150011 Yui Syt7_106d_M3 left abr_adaptation'
    fh = abr_adaptation.load(filename)

    # Extract the trains (rejecting artifacts and limiting to the number of
    # averages saved in the file) and cut them into repeats.
    trains = fh.get_trains_filtered(offset=-1e-3, repeat_duration=10e-3)
    repeats = fh.cut_repeats(trains, offset=-1e-3, duration=10e-3)

    # Or, in a single step.
    repeats = fh.get_repeats_filtered(offset=-1e-3, duration=10e-3)

'''
import logging
log = logging.getLogger(__name__)

import json

import numpy as np
import pandas as pd

from .abr import ABRFile


#: Largest fraction of a sample a repeat may be shifted by when cutting it out
#: of the train before we warn.
SAMPLE_TOLERANCE = 0.01


def epochs_fs(epochs):
    '''
    Sampling rate of a DataFrame of epochs (one column per timepoint)

    psidata stores the rate in `attrs`, but not every pandas operation
    preserves it, so we fall back to the spacing of the timepoints.
    '''
    if 'fs' in epochs.attrs:
        return epochs.attrs['fs']
    return 1 / np.diff(epochs.columns.values).mean()


def choose_downsample(fs, period, target_fs):
    '''
    Choose a decimation factor that keeps the repeats on whole samples

    The bursts in a train are a whole number of samples apart at the
    acquisition rate. After decimation, they are only on whole samples if the
    decimation factor divides that number. Otherwise, each repeat would have
    to be shifted by a fraction of a sample to cut it out of the train.

    Parameters
    ----------
    fs : float
        Sampling rate of the EEG.
    period : float
        Time between bursts, in seconds.
    target_fs : float
        The lowest acceptable sampling rate after decimation.

    Returns
    -------
    downsample : int
        The largest factor that does not drop the rate below `target_fs` and
        keeps the repeats on whole samples (1 if there is none).
    '''
    s_period = period * fs
    for q in range(max(1, int(fs // target_fs)), 0, -1):
        if abs(s_period / q - round(s_period / q)) < SAMPLE_TOLERANCE:
            return q
    return 1


class ABRAdaptationFile(ABRFile):
    '''
    Wrapper around an ABR adaptation file

    Parameters
    ----------
    base_path : string
        Path to folder containing ABR adaptation data
    '''

    def __init__(self, base_path, setting_table='erp_metadata'):
        super().__init__(base_path, setting_table)
        if 'abr_adaptation' not in self.base_path.stem:
            raise ValueError(f'{base_path} is not an ABR adaptation recording')

    @property
    def stimulus_type(self):
        '''
        Stimulus type used for ABR

        Returns
        -------
        stimulus_type
            'click' or 'tone' depending on stimulus used.
        '''
        return 'click' if 'abr_adaptation_click' in self.base_path.stem \
            else 'tone'

    @property
    def n_repeats(self):
        '''
        Number of bursts (or clicks) in each train
        '''
        return int(self.get_setting('n_bursts'))

    @property
    def rate(self):
        '''
        Requested rate, in bursts per second
        '''
        return self.get_setting('rate')

    @property
    def output_fs(self):
        '''
        Sampling rate of the output the trains were played through

        Falls back to the sampling rate of the EEG if the output cannot be
        found in the IO configuration.
        '''
        try:
            io = json.load(self._store._get_text_stream('io.json'))
        except Exception:
            log.warning('Could not load the IO configuration. Assuming the '
                        'output is sampled at the EEG rate.')
            return self.eeg.fs
        fs = _find_output_fs(io.get('output', {}), 'target')
        if fs is None:
            log.warning('Could not find the target output. Assuming the '
                        'output is sampled at the EEG rate.')
            return self.eeg.fs
        return fs

    @property
    def repeat_period(self):
        '''
        Time between the start of successive bursts, in seconds

        psiaudio places burst `i` at `i * round(fs / rate)` samples, so the
        actual period is a whole number of samples at the output rate and can
        differ slightly from `1 / rate`.
        '''
        fs = self.output_fs
        return round(fs / self.rate) / fs

    @property
    def repeat_t0(self):
        '''
        Start of each burst, in seconds, relative to the start of the train
        '''
        return np.arange(self.n_repeats) * self.repeat_period

    def get_train_duration(self, repeat_duration=10e-3):
        '''
        Duration of the train epoch needed to cut out every repeat

        The train epoch and the repeats share the same offset, so the train
        has to run from there to the end of the last repeat.

        Parameters
        ----------
        repeat_duration : float
            Duration of each repeat, in seconds.
        '''
        return self.repeat_t0[-1] + repeat_duration

    def get_trains(self, offset=-1e-3, repeat_duration=10e-3, **kwargs):
        '''
        Extract each train as a single epoch

        Parameters
        ----------
        offset : float
            Start of the epoch, in seconds, relative to the start of the
            train (i.e., the onset of the first burst). Use the same offset
            when cutting the train into repeats.
        repeat_duration : float
            The epoch is long enough to cut repeats of this duration from
            every burst in the train.
        **kwargs
            Passed to `ABRFile.get_epochs` (e.g., `reject_threshold`,
            `averages`, `columns` and `downsample`). Note that the reject
            applies to the whole train, as it does during acquisition.
        '''
        duration = self.get_train_duration(repeat_duration)
        return self.get_epochs(offset=offset, duration=duration, **kwargs)

    def get_trains_filtered(self, offset=-1e-3, repeat_duration=10e-3,
                            **kwargs):
        '''
        Extract each train as a single filtered epoch

        The train is filtered as a whole before it is cut into repeats so
        that each repeat is free of filter edge effects.

        Parameters
        ----------
        offset : float
            Start of the epoch, in seconds, relative to the start of the
            train (i.e., the onset of the first burst). Use the same offset
            when cutting the train into repeats.
        repeat_duration : float
            The epoch is long enough to cut repeats of this duration from
            every burst in the train.
        **kwargs
            Passed to `ABRFile.get_epochs_filtered` (e.g., `filter_lb`,
            `filter_ub`, `reject_threshold`, `averages`, `columns` and
            `downsample`). Note that the reject applies to the whole train, as
            it does during acquisition.
        '''
        duration = self.get_train_duration(repeat_duration)
        return self.get_epochs_filtered(offset=offset, duration=duration,
                                        **kwargs)

    def cut_repeats(self, trains, offset=-1e-3, duration=10e-3):
        '''
        Cut trains into one epoch per burst

        Parameters
        ----------
        trains : pd.DataFrame
            Train epochs as returned by `get_trains` or `get_trains_filtered`,
            one column per timepoint (in seconds re. the start of the train).
        offset : float
            Start of each repeat, in seconds, relative to burst onset. Must not
            be earlier than the start of the train epochs.
        duration : float
            Duration of each repeat, in seconds.

        Returns
        -------
        repeats : pd.DataFrame
            One row per repeat, indexed by the index of `trains` with `repeat`
            (the burst number, starting at 0) inserted before `t0` (the start
            of the train). Columns are time, in seconds, re. burst onset.
        '''
        fs = epochs_fs(trains)
        t_start = trains.columns.values[0]
        n_samples = int(round(duration * fs))
        t = np.arange(n_samples) / fs + offset

        # Exact (fractional) sample at which each repeat starts in the train.
        lb_exact = (self.repeat_t0 + offset - t_start) * fs
        lb = np.round(lb_exact).astype('i')
        shift = np.abs(lb_exact - lb).max()
        if shift > SAMPLE_TOLERANCE:
            log.warning('Repeats are shifted by up to %.2f samples to cut them '
                        'from the train. Choose a sampling rate at which the '
                        'burst period (%f sec) is a whole number of samples '
                        '(see `choose_downsample`).', shift,
                        self.repeat_period)
        if lb[0] < 0:
            raise ValueError('Repeat offset is earlier than the start of the '
                             'train epoch')
        if (lb[-1] + n_samples) > trains.shape[1]:
            raise ValueError('Train epoch is too short for the requested '
                             'repeat duration')

        values = trains.values
        repeats = np.stack([values[:, i:i+n_samples] for i in lb], axis=1)
        repeats = repeats.reshape(-1, n_samples)

        index = trains.index.to_frame(index=False)
        index = index.loc[index.index.repeat(self.n_repeats)]
        index.insert(index.columns.get_loc('t0'), 'repeat',
                     np.tile(np.arange(self.n_repeats), len(trains)))

        columns = pd.Index(t, name='time')
        result = pd.DataFrame(repeats, columns=columns,
                              index=pd.MultiIndex.from_frame(index))
        result.attrs['fs'] = fs
        return result

    def get_repeats(self, offset=-1e-3, duration=10e-3, **kwargs):
        '''
        Extract one epoch per burst

        Equivalent to `cut_repeats(get_trains(...))`. Keyword arguments are
        passed to `get_trains`.
        '''
        trains = self.get_trains(offset, duration, **kwargs)
        return self.cut_repeats(trains, offset, duration)

    def get_repeats_filtered(self, offset=-1e-3, duration=10e-3, **kwargs):
        '''
        Extract one filtered epoch per burst

        Equivalent to `cut_repeats(get_trains_filtered(...))`. Keyword
        arguments are passed to `get_trains_filtered`.
        '''
        trains = self.get_trains_filtered(offset, duration, **kwargs)
        return self.cut_repeats(trains, offset, duration)


def _find_output_fs(node, name):
    '''
    Find the sampling rate of the named output in the IO configuration
    '''
    if isinstance(node, dict):
        if node.get('name') == name and 'fs' in node:
            return node['fs']
        children = node.values()
    elif isinstance(node, list):
        children = node
    else:
        return None
    for child in children:
        if (fs := _find_output_fs(child, name)) is not None:
            return fs
    return None


def load(base_path):
    '''
    Load ABR adaptation data

    Parameters
    ----------
    base_path : string
        Path to folder

    Returns
    -------
    ABRAdaptationFile
    '''
    return ABRAdaptationFile(base_path)
